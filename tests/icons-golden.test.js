const CASES = [[EXP, 'exp'], [EXP, 'cat'], [INC, 'inc'], [WALLET, 'wallet']];

test('иконки: подбор совпадает с 1.0.4, кроме намеренных улучшений (CHANGES)', () => {
  const bad = [];
  CASES.forEach(([list, kind]) => list.forEach((n) => {
    const ch = CHANGES[kind] || {};
    const want = Object.prototype.hasOwnProperty.call(ch, n) ? ch[n] : Old.guessKind(n, kind);
    const got = Icons.guessKind(n, kind);
    if (got !== want) bad.push(kind + ' «' + n + '»: 1.0.4 ' + Old.guessKind(n, kind) + ', ждём ' + want + ', стало ' + got);
  }));
  assert.deepEqual(bad, []);
});

test('иконки: в CHANGES нет лишних строк (каждая отличается от 1.0.4 и есть в списке названий)', () => {
  const bad = [];
  const lists = { exp: EXP, cat: EXP, inc: INC, wallet: WALLET };
  Object.keys(CHANGES).forEach((kind) => Object.keys(CHANGES[kind]).forEach((n) => {
    if (lists[kind].indexOf(n) < 0) bad.push(kind + ' «' + n + '» нет в icons-names.js');
    else if (Old.guessKind(n, kind) === CHANGES[kind][n]) bad.push(kind + ' «' + n + '» совпадает с 1.0.4');
  }));
  assert.deepEqual(bad, []);
});
